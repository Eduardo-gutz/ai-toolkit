import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const RULES_HEADER = `# Project Rules

Generated by ai-toolkit. Do not edit by hand — run \`ai-toolkit sync\` to regenerate.

`;

/**
 * Walk source/rules/ and return rule files in alphabetical order.
 * @param {string} sourceDir
 * @returns {Array<{name: string, file: string, body: string}>}
 */
export function listRules(sourceDir) {
  const rulesDir = join(sourceDir, 'rules');
  if (!existsSync(rulesDir)) return [];

  const entries = readdirSync(rulesDir, { withFileTypes: true })
    .filter((f) => f.isFile())
    .filter((f) => f.name.endsWith('.md'))
    .filter((f) => !f.name.startsWith('_'))
    .map((f) => f.name)
    .sort();

  return entries.map((name) => {
    const file = join(rulesDir, name);
    return { name, file, body: readFileSync(file, 'utf8').trim() };
  });
}

/**
 * Render all rules into a single AGENTS.md body.
 * Rules are concatenated in alphabetical order, separated by horizontal rules.
 * @param {Array<{name: string, body: string}>} rules
 * @param {object} [options]
 * @param {string} [options.intro] - intro paragraph before rules
 * @returns {string} markdown body
 */
export function renderRules(rules, options = {}) {
  const parts = [RULES_HEADER];
  if (options.intro) {
    parts.push(options.intro);
    parts.push('');
  }
  for (let i = 0; i < rules.length; i++) {
    if (i > 0) parts.push('\n---\n');
    parts.push(rules[i].body);
    parts.push('');
  }
  return parts.join('\n');
}

/**
 * Generate Claude Code's CLAUDE.md that imports AGENTS.md.
 * Per WHY.md §4.2: opencode uses AGENTS.md; Claude Code uses CLAUDE.md that imports it.
 * @returns {string}
 */
export function renderClaudeMdImport() {
  return `# Claude Code rules

Generated by ai-toolkit. Do not edit by hand — run \`ai-toolkit sync\` to regenerate.

See [AGENTS.md](./AGENTS.md) for the full project rules.
`;
}